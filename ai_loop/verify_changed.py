#!/usr/bin/env python3
"""Run only the unit tests affected by the current changes (B-111 wrapper over B-105).

Computes the changed paths against a Git base (default: fork/ai-native,
including staged, unstaged and untracked files), selects the affected doctest
source files with tests/select_tests.py + tests/impact_map.json, and prints the
plan as JSON. With --run it also executes the selection on a built binary and
merges the B-101 report into the output.

Safety: anything the impact map cannot resolve (most of core/, build files,
docs, tools) falls back to the FULL suite, and the fallback reasons are always
shown. This is a development shortcut; the integration check before merge is
still the full suite (ai_loop/agent_finish.sh).

A full-suite catalog (B-101 JSON report) is required because selection is
validated against the tests that actually exist in the binary. Pass a saved
one with --catalog (see tests/README_SELECTION.md); without it, a fresh
catalog is generated by running the full suite once on --binary.

Examples:
    # Plan only, reusing a saved catalog.
    python3 ai_loop/verify_changed.py --catalog /tmp/uzu-catalog.json

    # Plan and run the selected tests on the standard loop binary.
    python3 ai_loop/verify_changed.py --catalog /tmp/uzu-catalog.json --run

Exit status: 0 for a printed plan; with --run, the engine's test status;
2 for invalid input or an incomplete run (same convention as select_tests.py).
"""

import argparse
import importlib.util
import json
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent

# Build-system files whose blast radius is the whole tree. They are unmapped
# in the impact map too, but name them explicitly so the fallback message
# says *why* the full suite runs.
WIDE_BASENAMES = {"SConstruct", "SCsub", "methods.py"}


def load_select_tests():
    spec = importlib.util.spec_from_file_location("uzu_select_tests", ROOT / "tests" / "select_tests.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def wide_impact_paths(changed: list[str]) -> list[str]:
    return sorted(path for path in changed if path.rsplit("/", 1)[-1] in WIDE_BASENAMES)


def generate_catalog(binary: Path) -> dict:
    """Run the full suite once via doctest_json.py and return its report."""
    with tempfile.TemporaryDirectory(prefix="uzu-verify-changed-") as directory:
        target = Path(directory) / "catalog.json"
        with target.open("w", encoding="utf-8") as output:
            subprocess.run(
                [sys.executable, str(ROOT / "tests" / "doctest_json.py"), str(binary.resolve())],
                stdout=output,
                check=False,
            )
        if not target.stat().st_size:
            raise ValueError("catalog generation produced no report; check the binary runs --test")
        return json.loads(target.read_text(encoding="utf-8"))


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--base", default="fork/ai-native", help="Git base revision (default: fork/ai-native)")
    parser.add_argument("--binary", type=Path, default=ROOT / "bin" / "godot.linuxbsd.editor.x86_64",
                        help="Built tests=yes editor binary (default: bin/godot.linuxbsd.editor.x86_64)")
    parser.add_argument("--catalog", type=Path, help="Saved full-suite B-101 JSON report; generated if omitted")
    parser.add_argument("--root", type=Path, default=ROOT, help="Git working tree to diff (default: this repo)")
    parser.add_argument("--run", action="store_true", help="Execute the selection; omit to print only the plan")
    options = parser.parse_args()
    try:
        select_tests = load_select_tests()
        changed = select_tests.git_changes(options.root, options.base)
        if options.catalog is not None:
            catalog = json.loads(options.catalog.read_text(encoding="utf-8"))
            catalog_source = str(options.catalog)
        else:
            if not options.binary.is_file():
                raise ValueError(f"binary not found and no --catalog given: {options.binary}")
            catalog = generate_catalog(options.binary)
            catalog_source = "generated (full suite run on --binary)"
        plan = select_tests.select(
            catalog,
            json.loads((ROOT / "tests" / "impact_map.json").read_text(encoding="utf-8")),
            changed,
        )
        wide = wide_impact_paths(changed)
        if wide and plan["mode"] == "selected":
            # A build-system change invalidates any narrow selection.
            plan["mode"] = "all"
            plan["test_files"] = sorted({select_tests.test_path(case["file"]) for case in catalog["test_cases"]})
            plan["doctest_args"] = []
            plan["fallback_reasons"] = plan["fallback_reasons"] + [
                "wide-impact build files changed: " + ", ".join(wide)
            ]
        output = {
            "ok": True,
            "base": options.base,
            "binary": str(options.binary),
            "catalog_source": catalog_source,
            "selection": plan,
        }
        if plan["mode"] == "all":
            print(
                "verify_changed: FULL suite selected (fallback). Reasons: "
                + ("; ".join(plan["fallback_reasons"]) or "none recorded"),
                file=sys.stderr,
            )
        else:
            print(
                f"verify_changed: {len(plan['test_files'])} test file(s) selected "
                f"for {len(plan['changed'])} changed path(s).",
                file=sys.stderr,
            )
        status = 0
        if options.run:
            if not options.binary.is_file():
                raise ValueError(f"binary not found: {options.binary}")
            report, status = select_tests.run_selection(options.binary, plan)
            output.update(report)
        json.dump(output, sys.stdout, ensure_ascii=False, indent=2)
        print()
        return status
    except (OSError, ValueError, KeyError, TypeError, subprocess.CalledProcessError) as error:
        print(json.dumps({"ok": False, "error": str(error)}))
        return 2


if __name__ == "__main__":
    sys.exit(main())
